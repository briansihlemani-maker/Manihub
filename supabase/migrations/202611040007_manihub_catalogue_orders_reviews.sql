-- ManiHub catalogue, checkout records and review foundation.
-- Additive only: preserves the existing listings table and existing storefront/messaging migrations.
-- Apply in Supabase SQL Editor after reviewing. Checkout writes must come from trusted server functions.

create table if not exists public.manihub_store_products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.manihub_stores(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  product_name text not null check (char_length(trim(product_name)) between 2 and 140),
  description text not null default '' check (char_length(description) <= 4000),
  category text not null default 'Other',
  price_zar numeric(12,2) not null check (price_zar >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  media_urls jsonb not null default '[]'::jsonb,
  status text not null default 'draft' check (status in ('draft','active','paused','out_of_stock','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(media_urls) = 'array')
);

create index if not exists manihub_store_products_store_idx on public.manihub_store_products(store_id,status);
create index if not exists manihub_store_products_owner_idx on public.manihub_store_products(owner_id,updated_at desc);
create index if not exists manihub_store_products_category_idx on public.manihub_store_products(category);

alter table public.manihub_store_products enable row level security;

drop policy if exists "Public can view active products in active stores" on public.manihub_store_products;
create policy "Public can view active products in active stores"
on public.manihub_store_products for select
using (
  status = 'active'
  and exists (
    select 1 from public.manihub_stores s
    where s.id = store_id and s.status = 'active'
  )
);

drop policy if exists "Owners can view all their products" on public.manihub_store_products;
create policy "Owners can view all their products"
on public.manihub_store_products for select to authenticated
using (owner_id = (select auth.uid()));

drop policy if exists "Owners can create their own products" on public.manihub_store_products;
create policy "Owners can create their own products"
on public.manihub_store_products for insert to authenticated
with check (
  owner_id = (select auth.uid())
  and exists (
    select 1 from public.manihub_stores s
    where s.id = store_id and s.owner_id = (select auth.uid())
  )
);

drop policy if exists "Owners can update their own products" on public.manihub_store_products;
create policy "Owners can update their own products"
on public.manihub_store_products for update to authenticated
using (owner_id = (select auth.uid()))
with check (
  owner_id = (select auth.uid())
  and exists (
    select 1 from public.manihub_stores s
    where s.id = store_id and s.owner_id = (select auth.uid())
  )
);

drop policy if exists "Owners can delete their own products" on public.manihub_store_products;
create policy "Owners can delete their own products"
on public.manihub_store_products for delete to authenticated
using (owner_id = (select auth.uid()));

create table if not exists public.manihub_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  buyer_id uuid not null references auth.users(id) on delete restrict,
  status text not null default 'pending_payment'
    check (status in ('pending_payment','paid','accepted','preparing','ready_for_collection','out_for_delivery','completed','cancelled','refunded','disputed')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid','pending','paid','partially_refunded','refunded','failed','disputed')),
  fulfilment_method text not null check (fulfilment_method in ('collection','delivery')),
  delivery_address jsonb,
  item_subtotal_zar numeric(12,2) not null check (item_subtotal_zar >= 0),
  delivery_fee_zar numeric(12,2) not null default 0 check (delivery_fee_zar >= 0),
  payment_service_fee_zar numeric(12,2) not null default 0 check (payment_service_fee_zar >= 0),
  total_zar numeric(12,2) not null check (total_zar >= 0),
  payment_transaction_id uuid references public.manihub_payment_transactions(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((fulfilment_method = 'collection' and delivery_fee_zar = 0) or fulfilment_method = 'delivery'),
  check (delivery_address is null or jsonb_typeof(delivery_address) = 'object')
);

create index if not exists manihub_orders_buyer_idx on public.manihub_orders(buyer_id,created_at desc);
create index if not exists manihub_orders_status_idx on public.manihub_orders(status,created_at desc);

create table if not exists public.manihub_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.manihub_orders(id) on delete restrict,
  store_id uuid not null references public.manihub_stores(id) on delete restrict,
  seller_id uuid not null references auth.users(id) on delete restrict,
  product_id uuid references public.manihub_store_products(id) on delete set null,
  product_name_snapshot text not null,
  unit_price_zar numeric(12,2) not null check (unit_price_zar >= 0),
  quantity integer not null check (quantity > 0),
  line_total_zar numeric(12,2) not null check (line_total_zar >= 0),
  created_at timestamptz not null default now()
);

create index if not exists manihub_order_items_order_idx on public.manihub_order_items(order_id);
create index if not exists manihub_order_items_seller_idx on public.manihub_order_items(seller_id,created_at desc);

create table if not exists public.manihub_order_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.manihub_orders(id) on delete restrict,
  actor_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  note text not null default '' check (char_length(note) <= 1500),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists manihub_order_events_order_idx on public.manihub_order_events(order_id,created_at);

create table if not exists public.manihub_product_reviews (
  id uuid primary key default gen_random_uuid(),
  order_item_id uuid not null references public.manihub_order_items(id) on delete restrict,
  product_id uuid references public.manihub_store_products(id) on delete set null,
  store_id uuid not null references public.manihub_stores(id) on delete restrict,
  reviewer_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text not null default '' check (char_length(review_text) <= 2000),
  status text not null default 'pending' check (status in ('pending','published','hidden')),
  created_at timestamptz not null default now(),
  unique (order_item_id,reviewer_id)
);

create index if not exists manihub_product_reviews_store_idx on public.manihub_product_reviews(store_id,status,created_at desc);
create index if not exists manihub_product_reviews_product_idx on public.manihub_product_reviews(product_id,status,created_at desc);

alter table public.manihub_orders enable row level security;
alter table public.manihub_order_items enable row level security;
alter table public.manihub_order_events enable row level security;
alter table public.manihub_product_reviews enable row level security;

-- SECURITY DEFINER membership helpers avoid recursive RLS policy evaluation
-- between order headers and order-item rows. They expose only boolean membership.
create or replace function public.manihub_is_order_buyer(p_order_id uuid)
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $
  select exists (
    select 1 from public.manihub_orders o
    where o.id = p_order_id and o.buyer_id = (select auth.uid())
  );
$;

create or replace function public.manihub_is_order_seller(p_order_id uuid)
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $
  select exists (
    select 1 from public.manihub_order_items oi
    where oi.order_id = p_order_id and oi.seller_id = (select auth.uid())
  );
$;

revoke all on function public.manihub_is_order_buyer(uuid) from public;
revoke all on function public.manihub_is_order_seller(uuid) from public;
grant execute on function public.manihub_is_order_buyer(uuid) to authenticated;
grant execute on function public.manihub_is_order_seller(uuid) to authenticated;

-- Orders and payment state are intentionally read-only to clients.
-- A trusted Edge Function/service role must create orders, validate prices/stock,
-- write order events, and update payment/fulfilment states.
drop policy if exists "Buyers and sellers can view relevant orders" on public.manihub_orders;
create policy "Buyers and sellers can view relevant orders"
on public.manihub_orders for select to authenticated
using (
  buyer_id = (select auth.uid())
  or public.manihub_is_order_seller(id)
);

drop policy if exists "Buyers and sellers can view relevant order items" on public.manihub_order_items;
create policy "Buyers and sellers can view relevant order items"
on public.manihub_order_items for select to authenticated
using (
  seller_id = (select auth.uid())
  or public.manihub_is_order_buyer(order_id)
);

drop policy if exists "Buyers and sellers can view relevant order events" on public.manihub_order_events;
create policy "Buyers and sellers can view relevant order events"
on public.manihub_order_events for select to authenticated
using (
  public.manihub_is_order_buyer(order_id)
  or public.manihub_is_order_seller(order_id)
);

drop policy if exists "Public can view published product reviews" on public.manihub_product_reviews;
create policy "Public can view published product reviews"
on public.manihub_product_reviews for select
using (status = 'published');

drop policy if exists "Reviewers can view their own reviews" on public.manihub_product_reviews;
create policy "Reviewers can view their own reviews"
on public.manihub_product_reviews for select to authenticated
using (reviewer_id = (select auth.uid()));

drop policy if exists "Verified buyers can submit reviews for paid orders" on public.manihub_product_reviews;
create policy "Verified buyers can submit reviews for paid orders"
on public.manihub_product_reviews for insert to authenticated
with check (
  reviewer_id = (select auth.uid())
  and exists (
    select 1
    from public.manihub_order_items oi
    join public.manihub_orders o on o.id = oi.order_id
    where oi.id = order_item_id
      and oi.order_id = o.id
      and o.buyer_id = (select auth.uid())
      and o.payment_status in ('paid','partially_refunded')
      and oi.store_id = public.manihub_product_reviews.store_id
      and oi.product_id is not distinct from public.manihub_product_reviews.product_id
  )
);

comment on table public.manihub_store_products is 'Store catalogue with owner-only writes and public active-store product reads.';
comment on table public.manihub_orders is 'Order header. All writes and price/stock validation must be performed by trusted backend functions.';
comment on table public.manihub_order_items is 'Immutable item/price snapshots per seller for auditable order fulfilment.';
comment on table public.manihub_order_events is 'Append-only order timeline written by trusted backend functions.';
comment on table public.manihub_product_reviews is 'Reviews are tied to a paid order item; moderation controls public visibility.';
